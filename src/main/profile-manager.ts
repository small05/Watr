/**
 * 浏览器环境 Profile 管理器 v1.2
 *
 * 管理指纹环境配置的 CRUD 操作：
 * - 内置"真机环境"Profile（默认，不可删除）
 * - 内置"Win10 预设"Profile（从 bot.sannysoft.com 检测数据提取）
 * - 用户自定义 Profile（可增删改）
 * - JSON 文件持久化到 portableRoot/profiles/
 */

import { promises as fs } from 'fs'
import { join } from 'path'

/** 浏览器环境配置 Profile */
export interface BrowserProfile {
  id: string
  name: string
  isBuiltin: boolean
  createdAt: string

  // ---- 可手动设置的类目 ----
  userAgent: string
  platform: string
  languages: string[]
  hardwareConcurrency: number
  deviceMemory: number

  screen: {
    width: number
    height: number
    colorDepth: number
    pixelDepth: number
    availWidth: number
    availHeight: number
    devicePixelRatio: number
  }

  webgl: {
    vendor: string
    renderer: string
  }

  mediaDevices: {
    speakers: number
    micros: number
    webcams: number
  }

  // ---- 自动变更的类目（每次启动自动生成） ----
  autoGenerated: {
    canvasNoiseSeed: number
    audioNoiseSeed: number
    webglNoiseSeed: number
    fontNoiseSeed: number
  }
}

/** 真机环境 Profile（所有值为空/0 代表直通宿主机真实硬件） */
