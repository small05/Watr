export class ProfileManager {
  private profilesDir: string
  private profiles: Map<string, BrowserProfile> = new Map()
  private activeProfileId: string = 'native'

  constructor(portableRoot: string) {
    this.profilesDir = join(portableRoot, 'profiles')
  }

  /** 初始化：创建目录 + 加载内置 Profile + 加载用户 Profile */
  async init(): Promise<void> {
    await fs.mkdir(this.profilesDir, { recursive: true })

    // 注册内置 Profile
    this.profiles.set(NATIVE_PROFILE.id, { ...NATIVE_PROFILE })
    this.profiles.set(WIN10_PRESET_PROFILE.id, { ...WIN10_PRESET_PROFILE })

    // 加载用户自定义 Profile
    try {
      const entries = await fs.readdir(this.profilesDir)
      for (const entry of entries) {
        if (!entry.endsWith('.json')) continue
        try {
          const raw = await fs.readFile(join(this.profilesDir, entry), 'utf-8')
          const profile: BrowserProfile = JSON.parse(raw)
          if (profile.id && !profile.isBuiltin) {
            this.profiles.set(profile.id, profile)
          }
        } catch { /* 跳过损坏的 Profile 文件 */ }
      }
    } catch { /* 目录不存在则忽略 */ }

    // 为非真机 Profile 重新生成噪声种子
    for (const [id, profile] of this.profiles) {
      if (id !== 'native') {
        profile.autoGenerated = this.generateNoiseSeeds()
      }
    }
  }

  /** 获取所有 Profile 列表 */
  listProfiles(): BrowserProfile[] {
    return Array.from(this.profiles.values())
  }

  /** 获取指定 Profile */
  getProfile(id: string): BrowserProfile | undefined {
    return this.profiles.get(id)
  }

  /** 获取当前活动 Profile */
  getActiveProfile(): BrowserProfile {
    return this.profiles.get(this.activeProfileId) || NATIVE_PROFILE
  }

  /** 获取活动 Profile ID */
  getActiveProfileId(): string {
    return this.activeProfileId
  }

  /** 设置活动 Profile */
  setActiveProfile(id: string): void {
    if (this.profiles.has(id)) {
      this.activeProfileId = id
    }
  }

  /** 获取 Win10 预设模板值（供 UI 编辑器使用） */
  getTemplateValues(): BrowserProfile {
    return { ...WIN10_PRESET_PROFILE }
  }

  /** 创建新的用户 Profile */
  async createProfile(profile: Omit<BrowserProfile, 'id' | 'isBuiltin' | 'createdAt' | 'autoGenerated'>): Promise<BrowserProfile> {
    const newProfile: BrowserProfile = {
      ...profile,
      id: `custom_${Date.now()}`,
      isBuiltin: false,
      createdAt: new Date().toISOString(),
      autoGenerated: this.generateNoiseSeeds()
    }

    this.profiles.set(newProfile.id, newProfile)
    await this.saveProfile(newProfile)
    return newProfile
  }

  /** 更新用户 Profile */
  async updateProfile(id: string, updates: Partial<BrowserProfile>): Promise<BrowserProfile | null> {
    const profile = this.profiles.get(id)
    if (!profile || profile.isBuiltin) return null

    // 合并更新（不允许修改 id, isBuiltin, autoGenerated）
    const updated: BrowserProfile = {
      ...profile,
      ...updates,
      id: profile.id,
      isBuiltin: false,
      autoGenerated: this.generateNoiseSeeds()  // 更新时重新生成噪声
    }

    this.profiles.set(id, updated)
    await this.saveProfile(updated)
    return updated
  }

  /** 删除用户 Profile */
  async deleteProfile(id: string): Promise<boolean> {
    const profile = this.profiles.get(id)
    if (!profile || profile.isBuiltin) return false

    this.profiles.delete(id)

    // 如果删除的是当前活动 Profile，切回真机
    if (this.activeProfileId === id) {
      this.activeProfileId = 'native'
    }

    try {
      await fs.unlink(join(this.profilesDir, `${id}.json`))
    } catch { /* 文件不存在则忽略 */ }

    return true
  }

  /** 持久化 Profile 到磁盘 */
  private async saveProfile(profile: BrowserProfile): Promise<void> {
    const filePath = join(this.profilesDir, `${profile.id}.json`)
    await fs.writeFile(filePath, JSON.stringify(profile, null, 2), 'utf-8')
  }

  /** 生成随机噪声种子（每次启动/应用时自动生成） */
  private generateNoiseSeeds() {
    return {
      canvasNoiseSeed: Math.floor(Math.random() * 2147483647),
      audioNoiseSeed: Math.floor(Math.random() * 2147483647),
      webglNoiseSeed: Math.floor(Math.random() * 2147483647),
      fontNoiseSeed: Math.floor(Math.random() * 2147483647)
    }
  }
}
